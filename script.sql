-- apaga as tabelas do NexRain se ja existirem (pode rodar o script quantas vezes quiser)
BEGIN
    FOR t IN (SELECT TABLE_NAME FROM USER_TABLES
              WHERE TABLE_NAME IN ('T_FIAP_ROTA_NR', 'T_FIAP_ALERTA_NR', 'T_FIAP_OCORRENCIA_NR',
                                   'T_FIAP_CAMERA_NR', 'T_FIAP_REGIAO_NR')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.TABLE_NAME || ' CASCADE CONSTRAINTS';
    END LOOP;
END;
/

-- bairros monitorados
CREATE TABLE T_FIAP_REGIAO_NR (
    ID_REGIAO        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NOME             VARCHAR2(80)  NOT NULL,
    CIDADE           VARCHAR2(60)  NOT NULL,
    LATITUDE         NUMBER(9,6)   NOT NULL,
    LONGITUDE        NUMBER(9,6)   NOT NULL,
    SUSCETIBILIDADE  VARCHAR2(10)  DEFAULT 'MEDIA' NOT NULL,
    LIMITE_CHUVA_MM  NUMBER(5,1)   DEFAULT 30 NOT NULL
);

-- cameras urbanas que alimentam a visao computacional
CREATE TABLE T_FIAP_CAMERA_NR (
    ID_CAMERA   NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_REGIAO   NUMBER        NOT NULL,
    NOME        VARCHAR2(80)  NOT NULL,
    ENDERECO    VARCHAR2(150) NOT NULL,
    LATITUDE    NUMBER(9,6)   NOT NULL,
    LONGITUDE   NUMBER(9,6)   NOT NULL,
    URL_IMAGEM  VARCHAR2(400),
    STATUS      VARCHAR2(15)  DEFAULT 'ATIVA' NOT NULL,
    CONSTRAINT FK_CAMERA_REGIAO_NR FOREIGN KEY (ID_REGIAO)
        REFERENCES T_FIAP_REGIAO_NR (ID_REGIAO) ON DELETE CASCADE
);

-- alagamentos identificados pela IA, informados por cidadaos ou cadastrados manualmente
CREATE TABLE T_FIAP_OCORRENCIA_NR (
    ID_OCORRENCIA   NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_REGIAO       NUMBER        NOT NULL,
    ID_CAMERA       NUMBER,
    ENDERECO        VARCHAR2(150) NOT NULL,
    LATITUDE        NUMBER(9,6)   NOT NULL,
    LONGITUDE       NUMBER(9,6)   NOT NULL,
    DATA_HORA       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    NIVEL_AGUA_CM   NUMBER(4)     DEFAULT 0 NOT NULL,
    NIVEL_RISCO     VARCHAR2(10)  NOT NULL,
    CONFIANCA       NUMBER(5,2)   DEFAULT 0,
    ORIGEM          VARCHAR2(20)  DEFAULT 'CIDADAO' NOT NULL,
    STATUS          VARCHAR2(15)  DEFAULT 'PENDENTE' NOT NULL,
    DESCRICAO       VARCHAR2(400),
    VALIDADO_POR    VARCHAR2(100),
    DATA_VALIDACAO  TIMESTAMP,
    CONSTRAINT FK_OCORRENCIA_REGIAO_NR FOREIGN KEY (ID_REGIAO)
        REFERENCES T_FIAP_REGIAO_NR (ID_REGIAO) ON DELETE CASCADE,
    CONSTRAINT FK_OCORRENCIA_CAMERA_NR FOREIGN KEY (ID_CAMERA)
        REFERENCES T_FIAP_CAMERA_NR (ID_CAMERA) ON DELETE SET NULL
);

-- alertas enviados aos cidadaos
CREATE TABLE T_FIAP_ALERTA_NR (
    ID_ALERTA        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_REGIAO        NUMBER        NOT NULL,
    ID_OCORRENCIA    NUMBER,
    TITULO           VARCHAR2(120) NOT NULL,
    MENSAGEM         VARCHAR2(500) NOT NULL,
    NIVEL            VARCHAR2(10)  NOT NULL,
    ORIGEM           VARCHAR2(20)  DEFAULT 'MANUAL' NOT NULL,
    DATA_EMISSAO     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    DATA_EXPIRACAO   TIMESTAMP     NOT NULL,
    ATIVO            CHAR(1)       DEFAULT 'S' NOT NULL,
    CONSTRAINT FK_ALERTA_REGIAO_NR FOREIGN KEY (ID_REGIAO)
        REFERENCES T_FIAP_REGIAO_NR (ID_REGIAO) ON DELETE CASCADE,
    CONSTRAINT FK_ALERTA_OCORRENCIA_NR FOREIGN KEY (ID_OCORRENCIA)
        REFERENCES T_FIAP_OCORRENCIA_NR (ID_OCORRENCIA) ON DELETE SET NULL
);

-- rotas seguras calculadas pelo algoritmo de desvio
CREATE TABLE T_FIAP_ROTA_NR (
    ID_ROTA                NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ORIGEM                 VARCHAR2(150) NOT NULL,
    ORIGEM_LAT             NUMBER(9,6)   NOT NULL,
    ORIGEM_LON             NUMBER(9,6)   NOT NULL,
    DESTINO                VARCHAR2(150) NOT NULL,
    DESTINO_LAT            NUMBER(9,6)   NOT NULL,
    DESTINO_LON            NUMBER(9,6)   NOT NULL,
    DISTANCIA_KM           NUMBER(7,2)   NOT NULL,
    DURACAO_MIN            NUMBER(7,1)   NOT NULL,
    DISTANCIA_DIRETA_KM    NUMBER(7,2),
    DURACAO_DIRETA_MIN     NUMBER(7,1),
    ALAGAMENTOS_EVITADOS   NUMBER(3)     DEFAULT 0,
    ALAGAMENTOS_NO_TRAJETO NUMBER(3)     DEFAULT 0,
    SITUACAO               VARCHAR2(15)  NOT NULL,
    TRAJETO                CLOB,
    TRAJETO_DIRETO         CLOB,
    DATA_CALCULO           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

